#!/usr/bin/env python3
# Expands every line of formats.txt with tmux 3.8 (display -p) on a
# scratch server and writes ../src/cases38.rs. The server and its options
# match the fake environment in src/tests.rs. Panes run sleep, never a
# shell, and no keys are sent.
#
# Run from anywhere: python3 -I format-spike/cases/gen.py

import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
TMUX = "/usr/bin/tmux"
SOCK = "/tmp/fs-%d" % os.getpid()
ENV = dict(os.environ, TZ="UTC")

OPTIONS = [
    ("@a", "hello"),
    ("@empty", ""),
    ("@zero", "0"),
    ("@one", "1"),
    ("@num", "42"),
    ("@path", "/usr/local/lib/libfoo.so.1"),
    ("@fmt", "#{@a}-#{@num}"),
    ("@hashv", "x#{@a}"),
    ("@sp", "it's a test"),
    ("@wide", "日本語x"),
    ("@style", "#[fg=red]ab#[default]cd"),
    ("@dollar", '$HOME "q"'),
    ("@t", "1700000000"),
    ("@tn", "#{?@one,%%%%,x}"),
    ("@pct", "100%%"),
    ("@rec", "#{E:@rec}"),
    ("@hash", "a#b"),
    ("status-right", "R"),
]


def tmux(*args, check=True):
    return subprocess.run(
        [TMUX, "-S", SOCK, "-f/dev/null", *args],
        env=ENV, capture_output=True, check=check,
    ).stdout


def rust_bytes(b):
    out = []
    for c in b:
        if c == 0x22:
            out.append('\\"')
        elif c == 0x5c:
            out.append("\\\\")
        elif 0x20 <= c < 0x7f:
            out.append(chr(c))
        else:
            out.append("\\x%02x" % c)
    return 'b"' + "".join(out) + '"'


def main():
    tmux("new", "-d", "-s", "main", "-n", "first", "-x", "80", "-y", "24", "sleep", "1000")
    try:
        tmux("neww", "-d", "-n", "second", "sleep", "1000")
        tmux("neww", "-n", "third", "sleep", "1000")
        tmux("selectw", "-t", ":1")
        tmux("selectw", "-t", ":2")
        for name, value in OPTIONS:
            tmux("set", "-g", name, value)
        with open(os.path.join(HERE, "formats.txt"), "rb") as f:
            formats = [l.rstrip(b"\n") for l in f if l.strip()]
        lines = []
        for fmt in formats:
            out = tmux("display", "-p", "-t", "main:", fmt.decode())
            if out.endswith(b"\n"):
                out = out[:-1]
            lines.append("    (%s, %s)," % (rust_bytes(fmt), rust_bytes(out)))
    finally:
        tmux("kill-server", check=False)
        if os.path.exists(SOCK):
            os.unlink(SOCK)
    path = os.path.join(HERE, "..", "src", "cases38.rs")
    with open(path, "w") as f:
        f.write("// Generated by cases/gen.py from tmux 3.8. Do not edit.\n\n")
        f.write("/// (format, what 3.8's display -p printed)\n")
        f.write("pub(crate) const CASES: &[(&[u8], &[u8])] = &[\n")
        f.write("\n".join(lines))
        f.write("\n];\n")
    print("%d cases" % len(lines), file=sys.stderr)


main()
